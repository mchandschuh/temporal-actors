// Package actor provides the definition and execution primitives for isolated
// stateful actors.
//
// An actor Definition is immutable code and handler registration shared by
// actor instances. An actor instance owns one identity and one explicit state
// value. The runtime-supported state transition is:
//
//	nextState = handler(context, state, message)
//
// Definitions do not own actor state, and handlers must not use mutable
// closures, receivers, package variables, or Context fields as hidden actor
// state. Handler code must be deterministic and replay-safe.
//
// Commands and requests are both intended to be processed through one actor's
// serialized mailbox. Commands return the next state. Requests return a result
// and leave the state unchanged. A request is therefore different from a
// Temporal Query: a sequenced request observes messages that precede it in the
// mailbox.
//
// Handler lookup is based on the runtime Go message type. Exact types take
// precedence over assignable interfaces, and more-specific interfaces take
// precedence over broader interfaces. Ambiguous matches are errors. Marker
// interfaces are optional domain organization and are not required by this
// package.
//
// Actor identity names generated by this repository use an explicit v1 naming
// convention. That convention is a durable compatibility boundary for live
// Temporal executions; changing it requires a new convention and a migration
// strategy rather than an incidental refactor.
package actor
